    # Здесь стояли `workstation_unavailable` и `charging_unavailable` (тип
    # `UNAVAILABLE`): вариантов у них нет, текст не принимается, запись
    # невозможна — и **наполнить их из веба тоже нельзя**, потому что
    # `add_option` отказывает для этого типа. Оставить их значило бы держать в
    # дереве два мёртвых узла, на которые уже никто не ссылается, — а валидатор
    # справедливо запрещает недостижимые узлы.
    #
    # Константы `WORKSTATION_UNAVAILABLE` / `CHARGING_UNAVAILABLE` с текстами
    # **оставлены**: если ветку когда-нибудь снова закроют, текст уже написан, и
    # восстановить узел будет чем. Удалять текст вместе с узлом значило бы
