        # QR пошёл бы выбирать модель робота.
        #
        # **Ветки зарядки здесь нет.** Раньше стояло
        # `next_node_by_kind=((KIND_STATION, ASK_CHARGING_ROBOT),)`: после номера
        # станции спрашивался робот. Сама ветка убрана из дерева владельцем
