    # Шаг 5: причина ошибки — **свой узел на каждый модуль**
    # ------------------------------------------------------------
    # **Владелец: «добавить причину ошибки как ещё один вопрос».** Это не
    # повтор описания: описание отвечает «что не так» («не поднимает вилы»),
    # причина — «почему» («наехал на посторонний предмет»). Раньше причина не
    # спрашивалась, поэтому в отчётах её не было, и разбор повторяющихся ошибок
    # упирался в догадки.
    #
    # **Владелец 13.10.2026: «сделай Block What caused it? на каждый модуль».**
    # Причина осмысленна только в контексте железа: «погнул вилы» не бывает у
    # шасси, а «наехал на посторонний предмет» — у камеры. Общий список заставлял
    # оператора выбирать неточное и портил статистику.
    #
    # **Почему отдельные узлы, а не `only_for`.** Тот же довод, что у узлов
    # модулей (см. `ROBOT_MODULES`): `only_for` фильтрует варианты **одного**
    # узла, а здесь у каждого модуля свой список **и своя связь с заготовкой** —
    # фильтром её не выразить. Плюс валидатор запрещает одинаковые id вариантов
    # внутри узла, и разные узлы снимают это ограничение честно.
    #
    # **Список у каждого модуля свой, и это не «копия одного и того же».** В
    # стартовом наборе общие причины (человек, износ, прошивка) стоят у всех —
    # они действительно бывают везде; а «наехал на посторонний предмет» только у
    # движущихся модулей, «повреждён код места» только у QR. Правится через
    # редактор (`/tree` и веб), как и остальные узлы.
    #
    # «Other» оставлен у каждого модуля намеренно: закрытый список без него
    # заставляет выбирать неточное и портит статистику.
    #
    # **Ведёт по-разному в зависимости от варианта** (решение владельца
    # 12.10.2026): `Other` — на свободное описание, все остальные причины —
    # сразу к итогу. Это и есть «описание нужно только если other выберет».
    #
    # 🔴 **id причин повторяются между модулями** (`human_error` есть у всех).
    # Это безопасно, потому что связь с заготовкой хранится **с узлом**
    # (`node_id` + `option_id`), а не по одному `option_id`: иначе связь,
    # выставленная на причине шасси, «уехала» бы на причину подъёма.
    for cause_module in MODULE_ERRORS:
        add(choice_node(
            cause_node_id(cause_module),
            f"{ERROR_MODULE_TITLES[cause_module]}: what caused it?",
            key="cause",
            summary_label="Cause",
            description="Why it happened — helps to prevent a repeat.",
            options=tuple(
                opt(option_id, label, SUMMARY)
                for option_id, label in CAUSE_OPTIONS.get(
                    cause_module, CAUSE_OPTIONS["_default"]
                )
            ) + (
                # Единственная причина, ведущая на описание: своего варианта у
                # неё нет, и слова оператора — единственный источник подробностей.
                opt("other", "Other", ASK_DESCRIPTION),
            ),
        ))

    # ------------------------------------------------------------
    # Зарядки и станции — рабочие ветки
    # ------------------------------------------------------------
    # **Первый номер зарядки** — отдельный узел, а не общий `ask_number`: у него
    # своя подсказка и он ведёт не к модели, а ко **второму** номеру (робота).
    # Общий узел здесь не подошёл бы: `ask_number` дальше спрашивает модель
    # робота, которой у зарядки нет.
    add(Node(
        id=ASK_CHARGING_NUMBER,
        title="Charging station number",
        type=NodeType.INPUT,
        key="device_number",
        summary_label="Charging station",
        description="The number printed on the charging station.",
        placeholder="For example: 137",
        answer_kind=KIND_STATION,
        next_node=ASK_CHARGING_ROBOT,
    ))

    # **Номер рабочей станции.** Как у зарядки — отдельный узел, а не общий
    # `ask_number`: у станции своя подсказка (`C2-H146`), и ведёт она не к
    # модели робота, а сразу к списку проблем.
    add(Node(
        id=ASK_WORKSTATION_NUMBER,
        title="Workstation code",
        type=NodeType.INPUT,
        key="device_number",
        summary_label="Workstation",
        description="The code printed on the workstation.",
        placeholder="For example: C2-H146",
        answer_kind=KIND_WORKSTATION,
        next_node=device_problem_node_id(WORKSTATION_TAIL),
    ))

    # **Второй номер — робот, стоявший на станции.** Записываются оба: станция в
    # `device_number`, робот в `robot_number`. Без второго номера в отчёте нельзя
    # понять, с каким роботом была проблема.
    add(Node(
        id=ASK_CHARGING_ROBOT,
        title="Robot number",
        type=NodeType.INPUT,
        # 🔴 **Ключ `error_robot` — тот, который читает отчёт.**
        #
        # Сначала здесь стояло `charging_robot`, и номер робота **терялся**:
        # `build_rows` берёт его из `answers["error_robot"]`, а движок кладёт
        # ответ под `node.key`. Проверено на живом прогоне: зарядка `137` +
        # робот `3780` давали `robot_number: 137` — то есть номер станции
        # попадал в колонку робота, и связь «зарядка ↔ робот» пропадала.
        #
        # Имя историческое (`error_robot` → колонка `robot_number`), но менять
        # его нельзя: на него завязаны `NUMBER_KEYS`, проверка формата и запись
        # отчёта. Одно имя на все три места.
        key="error_robot",
        summary_label="Robot",
        description="The robot that was on the charging station.",
        placeholder="For example: 3780 or H108/1834",
        # Вид номера — робот: подсказка и проверка формата берутся для робота,
        # хотя ветка зарядки. Иначе оператор увидел бы пример номера станции и
        # ввёл станцию второй раз.
        answer_kind=KIND_ROBOT,
        # **Обязателен, и это осознанно.** Спросить «какой робот стоял» и
        # разрешить пропуск — значит потерять связь «зарядка ↔ робот» ровно в
        # тех случаях, когда она и нужна: оператор пропустит шаг, не вспомнив
        # номер, а разбираться придётся ��о описанию.
        #
        # Если робот действительно неизвестен, оператор напишет это в описании
        # причины («Other» → свободный текст), а не оставит поле пустым молча.
        next_node=device_problem_node_id(CHARGING_TAIL),
    ))
    # 🔴 **Построены по образцу робота, но без слоя модулей.** У зарядки и
    # станции нет «шасси» и «подъёма»: список проблем идёт сразу, а причина
    # спрашивается отдельным вопросом.
    #
    # **Почему причина спрашивается, а не берётся из проблемы.** «Не заряжает» —
    # это **что** случилось, а «износ» или «ошибка человека» — **почему**. В
    # отчёте это разные колонки, и раньше причину не спрашивали вовсе, поэтому
    # в статистике её не было.
    #
    # **Почему узлы строятся циклом по данным.** Списки проблем и причин правятся
    # в вебе; держать их в двух местах (данные и разметка узлов) значило бы
    # расхождение: добавили проблему в список — а кнопка не появилась.
    for tail, problems, causes, title in (
        (
            CHARGING_TAIL,
            CHARGING_PROBLEMS,
            CHARGING_CAUSES,
            "Charging station",
        ),
        (
            WORKSTATION_TAIL,
            WORKSTATION_PROBLEMS,
            WORKSTATION_CAUSES,
            "Workstation",
        ),
    ):
        # Узел причин — **до** узла проблем: проблема ведёт на него, и порядок
        # объявления делает связь читаемой при разборе дерева.
        add(choice_node(
            cause_node_id(tail),
            f"{title}: what caused it?",
            key="cause",
            summary_label="Cause",
            description="Why it happened — helps to prevent a repeat.",
            options=tuple(
                opt(option_id, label, SUMMARY) for option_id, label in causes
            )
            + (
                # «Other» есть у каждого устройства: закрытый список без него
                # заставляет выбирать неточное и портит статистику.
                opt("other", "Other", ASK_DESCRIPTION),
            ),
        ))

        add(choice_node(
            device_problem_node_id(tail),
            f"{title}: what is wrong?",
            key="problem",
            summary_label="Problem",
            description="What exactly is wrong with this unit.",
            options=tuple(
                # **Проблема ведёт на причину своего устройства.** Именно так
                # заготовка привязывается к осмысленному шагу: в отчёт попадают
                # тип ошибки, «что сделано» и время решения **причины**.
                opt(option_id, label, cause_node_id(tail))
                for option_id, label in problems
            ),
        ))

    # ------------------------------------------------------------
    # Финал
    # ------------------------------------------------------------
    add(Node(
        id=SUMMARY,
        title="Inspection result",
        type=NodeType.FINAL,
        summary_title="Inspection result",
        final_action="save_inspection",
    ))

    return nodes


