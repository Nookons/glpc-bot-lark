"""
Раскладка кнопок Telegram: **не больше двух рядов**, иначе они не читаются.

Требование владельца 13.10.2026, дословно: «Сделай по всему боту чтобы было не
больше двух рядов кнопок в противном случае они не читаются». Уточнение того же
дня: в лимит считаются **ряды вариантов**, а ряд навигации (Next / Back /
Cancel) идёт **отдельно** внизу.

─── Зачем отдельный модуль ──────────────────────────────────────────────────

Правило «два ряда» жило только в дереве приёма (`equipment_intake/keyboards.py`),
а **остальные экраны бота** ставили по одной кнопке в ряд. Замерено на живых
данных 13.10.2026:

    экран                     было рядов   почему
    ─────────────────────────────────────────────────────────────────────
    статус робота (offline)        6        по одной кнопке в ряд
    статус робота (online)         6        по одной кнопке в ряд
    меню типа ошибки             N + 1      по одной кнопке в ряд
    выбор склада                 N + 1      по одной кнопке в ряд
    исправить номер робота       K + 1      по одной кнопке в ряд
    частые номера роботов          3        4 в ряд + Cancel

Шесть рядов причин на экране статуса — это тот самый случай, когда кнопки «не
читаются»: они уезжают вверх за пределы экрана, и оператор видит не весь выбор.

─── Что здесь есть ──────────────────────────────────────────────────────────

`grid_rows()` — раскладка готовых кнопок в сетку: **не больше `max_rows` рядов**
(по умолчанию два). Остальное не выбрасывается: `paginate()` отдаёт одну
страницу и говорит, сколько их всего, а `pager_row()` рисует ряд листания.

`columns_for_labels()` — ширина ряда **по длине подписей**. Шесть колонок
читаются только у коротких подписей (`Chassis`, `A42T C2`); у длинных
(«Safety controller issues», 24 знака) шесть колонок дают `Safety…`, и выбор
становится нечитаемым — ровно то, на что владелец жаловался 12.10.2026.
"""

from __future__ import annotations

from typing import Dict, List, Sequence

#: Больше двух рядов кнопок на экране — предел владельца (13.10.2026).
MAX_OPTION_ROWS = 2

#: Сколько кнопок в ряду, когда подписи **короткие**: требование «6 в ряд».
DEFAULT_COLUMNS = 6

#: 🔴 **Ширина одного ряда кнопок в «единицах ширины глифа».**
#:
#: Замерено по **скриншоту владельца** от 13.10.2026 (телефон, 6 колонок):
#:
#:     [Chass…] [Lifting…] [Rotati…] [Tray →] [Horn …] [Hook …]
#:     [    QR Code →    ] [     Safety →     ]
#:     [              Cancel              ]
#:
#: Из него видно **два факта**, которые и определяют раскладку:
#:
#: 1. **Telegram ОБРЕЗАЕТ текст кнопки многоточием, а не переносит его.**
#:    До этой правки я считал «ряды вариантов» и был уверен, что всё в порядке:
#:    рядов действительно не больше двух. Владелец при этом видел `Chass…` и
#:    `Rotati…` — **выбор невозможно прочитать**. Считать надо ширину текста.
#: 2. **Обрезка по пиксельной ширине, а не по числу знаков.** `Tray →` (7 знаков)
#:    влезло, а `Horn →` (тоже 7) — нет: `Horn` шире `Tray` в пропорциональном
#:    шрифте. Поэтому модель считает **ширину глифов** (`_units`), а не `len()`.
#:
#: Проверка калибровки — тест `test_calibrated_against_the_owner_screenshot`:
#: модель обязана объяснить **все** восемь кнопок со снимка.
#:
#: **Значение выведено из снимка, а не выбрано на глаз.** При шести колонках
#: `Tray →` влезло, `Horn →` — нет, значит ёмкость кнопки лежит строго между их
#: ширинами: `ROW/6 - 2*PAD` ∈ (5.35; 5.65] → `ROW` ∈ (50.1; 51.9]. Взято 51.
ROW_UNITS = 51.0

#: Отступ внутри кнопки (padding) в тех же единицах: он «съедается» дважды —
#: слева и справа, поэтому вычитается как `2 * BUTTON_PADDING_UNITS`.
BUTTON_PADDING_UNITS = 1.5

#: Сколько кнопок в ряду, когда подписи **короткие**: требование «6 в ряд».
#: Оставлено ради совместимости: фактическая ширина считается по тексту.
SINGLE_LINE_LABEL_LIMIT = 12

#: Сколько колонок ставить, когда подписи длиннее предела: треть ширины экрана
#: даёт ≈14–16 знаков, длинная подпись переносится, но читается целиком.
WIDE_LABEL_COLUMNS = 3


#: Ширина глифа в единицах, где обычная строчная буква = 1.0.
#:
#: **Зачем вообще модель, а не `len()`.** Telegram рисует пропорциональным
#: шрифтом: `Tray` и `Horn` — по четыре знака, но `Horn` шире, и на скриншоте
#: владельца `Tray →` читается целиком, а `Horn →` уже обрезан. Счёт по знакам
#: этого не объясняет и **даёт неверную ширину ряда** — именно так `Chassis`
#: оказался в ряду из шести.
#:
#: Значения — прикидка по метрикам системного шрифта Telegram (San Francisco /
#: Roboto): узкие глифы (`i`, `l`, `t`, `f`, пробел) ≈0.45, широкие (`m`, `w`)
#: ≈1.3, узкие заглавные (`I`, `J`, `T`) ≈0.9, широкие (`M`, `W`, `H`) ≈1.2.
_GLYPH_UNITS = {
    **{c: 0.45 for c in "iljtfr.,:;!|'` "},
    **{c: 1.30 for c in "mw"},
    **{c: 0.90 for c in "TIJ"},
    **{c: 1.20 for c in "HMW"},
    # Стрелка «ведёт дальше» — часть текста кнопки, и её ширину тоже надо
    # учитывать: она съедает почти два знака, а до этой правки не считалась
    # вовсе (ширина ряда выводилась по `option.label` **без** стрелки).
    "→": 1.10,
    "←": 1.10,
    "◀": 1.10,
    "▶": 1.10,
    "✓": 1.00,
}


def glyph_units(text: str) -> float:
    """Ширина текста в «единицах глифа» (обычная строчная = 1.0)."""
    total = 0.0

    for char in str(text or ""):
        if char in _GLYPH_UNITS:
            total += _GLYPH_UNITS[char]
        elif char.isupper():
            total += 1.05
        elif char.isdigit():
            total += 0.90
        else:
            total += 1.00

    return total


def fits_columns(labels: Sequence[str], columns: int) -> bool:
    """Влезают ли **все** подписи в кнопку при таком числе колонок."""
    width = max(1, int(columns))
    capacity = ROW_UNITS / width - 2 * BUTTON_PADDING_UNITS

    return all(glyph_units(label) <= capacity for label in labels)

#: Текст кнопок листания.
BACK_LABEL = "◀ Back"
NEXT_LABEL = "Next ▶"


def columns_for_labels(labels: Sequence[str]) -> int:
    """
    Сколько кнопок ставить в ряд, чтобы **ни одна подпись не обрезалась**.

    🔴 **Что здесь было не так (исправлено 13.10.2026).**

    Считалось `len(label)`: «длиннее 12 знаков — ставим три колонки, иначе
    шесть». На живом экране это давало `[Chass…] [Lifting…] [Rotati…]` — владелец
    прислал скриншот с «вот видишь что за хрень». Две ошибки в одной строке:

    1. **Обрезка идёт по ширине текста, а не по числу знаков.** `Tray →` (7
       знаков) влезло, `Horn →` (тоже 7) — нет.
    2. **Стрелка `→` не считалась вообще.** Код дописывает её к подписи
       (`_button`), а ширина выводилась по `option.label` без неё — то есть
       кнопка планировалась уже, чем рисовалась.

    **Новое правило.** Берём **самое широкое** число колонок от 6 вниз, при
    котором **все** подписи влезают целиком (`fits_columns`). Причины и ошибки с
    длинными подписями получат 2–3 колонки, модули — 4, короткие подписи — 6.
    Требование владельца «два ряда по 6» остаётся там, где подписи короткие.

    **Почему выравнивание по худшей подписи, а не по средней.** Одна обрезанная
    подпись в ряду делает выбор неоднозначным: оператор видит `Horn …` и не
    знает, `Horn` там или `Hook`. Ряд обязан читаться **целиком**.
    """
    labels = [str(label or "") for label in labels]

    if not labels:
        return DEFAULT_COLUMNS

    for columns in range(DEFAULT_COLUMNS, 1, -1):
        if fits_columns(labels, columns):
            return columns

    # Даже в одну колонку подпись шире экрана — обрезать всё равно придётся:
    # Telegram не даёт многострочных кнопок. Отдаём минимум.
    return 1


def rows_per_page(columns: int) -> int:
    """Сколько кнопок помещается на страницу при такой ширине ряда."""
    return max(1, int(columns)) * MAX_OPTION_ROWS


def page_count(total: int, columns: int) -> int:
    """
    Сколько страниц нужно для `total` кнопок (минимум одна).

    Страница пустой не бывает: даже при нуле кнопок возвращается `1`, чтобы
    вызывающий код не делил на ноль и не рисовал «страницу 1 из 0».
    """
    per_page = rows_per_page(columns)

    if total <= 0:
        return 1

    return (total + per_page - 1) // per_page


def clamp_page(page: int, total: int, columns: int) -> int:
    """Приводит номер страницы к допустимому диапазону."""
    try:
        value = int(page)
    except (TypeError, ValueError):
        value = 0

    return max(0, min(value, page_count(total, columns) - 1))


def paginate(
    items: Sequence,
    columns: int,
    page: int = 0,
) -> Dict[str, object]:
    """
    Одна страница списка: что показать, какая это страница и сколько их всего.

    **Почему страницами, а не обрезкой.** Если вариантов больше, чем влезает в
    два ряда, выбросить остальные нельзя: оператор не смог бы выбрать то, что
    ему нужно. Поэтому лишнее уходит на следующую страницу, а не пропадает.
    """
    total_pages = page_count(len(items), columns)
    current = clamp_page(page, len(items), columns)
    per_page = rows_per_page(columns)

    start = current * per_page

    return {
        "items": list(items[start : start + per_page]),
        "page": current,
        "pages": total_pages,
        "per_page": per_page,
    }


def grid_rows(
    buttons: Sequence[Dict[str, str]],
    columns: int = DEFAULT_COLUMNS,
    max_rows: int = MAX_OPTION_ROWS,
) -> List[List[Dict[str, str]]]:
    """
    Раскладка готовых кнопок в сетку: не больше `max_rows` рядов.

    Возвращает **только** ряды вариантов — ряд навигации вызывающий код
    добавляет сам. Это и есть уточнение владельца: в лимит входят ряды
    вариантов, а Next / Back / Cancel идут отдельно внизу.

    Кнопки сверх лимита **не теряются молча в никуда**: их отбрасывает эта
    функция, поэтому вызывающий код обязан сперва отдать список в `paginate`
    и передать сюда уже страницу. Если пришло больше, чем влезает, — это
    дефект вызова, и о нём честно сообщает `overflow()` ниже.
    """
    width = max(1, int(columns))
    limit = width * max(1, int(max_rows))

    rows: List[List[Dict[str, str]]] = []

    for index in range(0, min(len(buttons), limit), width):
        rows.append(list(buttons[index : index + width]))

    return rows


def overflow(buttons: Sequence, columns: int, max_rows: int = MAX_OPTION_ROWS) -> int:
    """
    Сколько кнопок **не поместилось** (0 — поместились все).

    Нужна тестам и проверкам: раскладка молча обрезает лишнее, и без такого
    счётчика «обрезали» и «поместились» выглядели бы одинаково.
    """
    limit = max(1, int(columns)) * max(1, int(max_rows))

    return max(0, len(buttons) - limit)


def pager_row(page: int, pages: int, prefix: str) -> List[Dict[str, str]]:
    """
    Ряд листания: Back (если есть предыдущая) и Next (если есть следующая).

    `prefix` — начало `callback_data` без завершающего двоеточия, например
    `"em:p"`. Номер страницы дописывается третьим полем.

    В ряду не больше двух кнопок, поэтому «далее» всегда стоит **отдельным
    рядом** под вариантами — как и просил владелец 12.10.2026.
    """
    if pages <= 1:
        return []

    buttons: List[Dict[str, str]] = []

    if page > 0:
        buttons.append({
            "text": f"{BACK_LABEL} {page}/{pages}",
            "callback_data": f"{prefix}:{page - 1}",
        })

    if page < pages - 1:
        buttons.append({
            "text": f"{NEXT_LABEL} {page + 2}/{pages}",
            "callback_data": f"{prefix}:{page + 1}",
        })

    return buttons
